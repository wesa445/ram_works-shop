// Уровень качества — один на всё приложение. На сенсорных устройствах (телефоны, планшеты)
// видеокарта в 5–15 раз слабее десктопной, а экран плотнее — кадр там лагал.
//
// Замер GPU-времени на телефонном разрешении 390×844 при DPR 1.5 (GTX 1060, мс на кадр, 2026-09-27):
// всё включено 5.3; без дымки 2.7; без ореола 3.2; простые материалы вместо физических 3.2;
// без теней и без пылинок — почти без разницы. Отсюда рычаги ниже; тени и пыль не трогаем.
export const TOUCH = (() => {
  try {
    return window.matchMedia('(pointer: coarse)').matches
  } catch {
    return false
  }
})()

export const QUALITY = TOUCH
  ? {
      maxDpr: 1.5,
      hazeSteps: 12,
      hazeScale: 0.5, // дымка считается в половинном разрешении — вчетверо меньше пикселей
      bloom: false, // ореол — треть кадра, а у дымки своё свечение
      lambert: true, // все неметаллы без блика: физический материал — ещё треть кадра
      fpsCap: 60, // экраны 90–120 Гц: браузер зовёт кадр чаще, чем нужно глазу
      shadowMap: 1024,
      shadowEvery: 6, // пока куртка крутится, тени пересчитываются раз в столько кадров
    }
  : { maxDpr: 2, hazeSteps: 24, hazeScale: 1, bloom: true, lambert: false, fpsCap: 0, shadowMap: 2048, shadowEvery: 1 }
